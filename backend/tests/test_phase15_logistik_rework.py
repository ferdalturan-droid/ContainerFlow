# Test 4: Driver cannot release an admin-assigned tour
# --------------------------------------------------------------------------
def test_driver_cannot_release_admin_assigned_tour(tokens):
    if not tokens.get("dr"):
        pytest.skip("driver token unavailable")
    tid = None
    try:
        # LA creates a tour and assigns to driver (use the driver's own id)
        body = {
            "date": "2026-06-19",
            "fraction": "TEST_p15_lock_frac",
            "facility": "TEST_p15_LOCK_FAC",
            "address": "TEST_p15_addr",
            "plads": "TEST_p15_plads",
            "customer_code": "LCK",
            "customer_name": "Lock Test",
            "tour_type": "normal",
        }
        r = requests.post(f"{API}/tours", headers=H(tokens["la"]), json=body, timeout=15)
        assert r.status_code == 200, r.text
        tid = r.json()["id"]

        # find driver id matching test2
        drivers = requests.get(f"{API}/drivers", headers=H(tokens["la"]), timeout=10).json()
        # Try to match by username/email containing 'test2' or 'testc'
        target = None
        for d in drivers:
            uname = (d.get("username") or d.get("email") or d.get("name") or "").lower()
            if "test2" in uname or "testc" in uname:
                target = d
                break
        if not target and drivers:
            target = drivers[0]
        if not target:
            pytest.skip("No driver found")
        driver_id = target.get("id")
        driver_name = target.get("name") or "testc"

        # LA pre-assigns + claims for driver (simulate admin assignment)
        ra = requests.put(
            f"{API}/tours/{tid}",
            headers=H(tokens["la"]),
            json={
                "driver_id": driver_id,
                "driver_name": driver_name,
                "claimed_by": driver_name,
                "claimed_by_id": driver_id,
            },
            timeout=15,
        )
        assert ra.status_code == 200, ra.text
        assigned = ra.json()
        assert assigned.get("assigned_by_id"), assigned

        # Driver tries to release with claimed_by=""
        rd = requests.put(
            f"{API}/tours/{tid}",
            headers=H(tokens["dr"]),
            json={"claimed_by": "", "claimed_by_id": ""},
            timeout=15,
        )
        assert rd.status_code == 403, f"driver should be 403 trying to release admin tour, got {rd.status_code}: {rd.text}"
        body_text = rd.text.lower()
        assert "tildelt af administrator" in body_text or "kontakt din logistikadmin" in body_text, rd.text
    finally:
        if tid:
            requests.delete(f"{API}/tours/{tid}", headers=H(tokens["la"]), timeout=10)


