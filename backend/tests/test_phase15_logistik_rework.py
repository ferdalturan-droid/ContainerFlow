# Test 2: bulk-assign — role gating + assignment tracking
# --------------------------------------------------------------------------
def test_bulk_assign_role_gating_and_audit(tokens):
    """LA can bulk-assign; driver gets 403. assigned_by_* fields populated."""
    # Create 2 tours as LA
    created_ids = []
    try:
        for i in range(2):
            body = {
                "date": "2026-06-19",
                "fraction": f"TEST_p15_ba_{i}",
                "facility": "TEST_p15_BA_FAC",
                "address": "TEST_p15_addr",
                "plads": "TEST_p15_plads",
                "customer_code": "BAX",
                "customer_name": "BulkAssign Test",
                "tour_type": "normal",
            }
            r = requests.post(f"{API}/tours", headers=H(tokens["la"]), json=body, timeout=15)
            assert r.status_code == 200, r.text
            created_ids.append(r.json()["id"])

        # Find an available driver (use any from /api/drivers)
        rdv = requests.get(f"{API}/drivers", headers=H(tokens["la"]), timeout=10)
        assert rdv.status_code == 200, rdv.text
        drivers = rdv.json()
        if not drivers:
            pytest.skip("No drivers available to assign")
        driver_id = drivers[0].get("id") or drivers[0].get("user_id") or ""
        driver_name = drivers[0].get("name") or drivers[0].get("display_name") or "TestDriver"
        assert driver_id, drivers[0]

        # Driver attempt should be 403
        if tokens.get("dr"):
            rd = requests.post(
                f"{API}/tours/bulk-assign",
                headers=H(tokens["dr"]),
                json={"tour_ids": created_ids, "driver_id": driver_id, "driver_name": driver_name},
                timeout=15,
            )
            assert rd.status_code == 403, f"driver bulk-assign should be 403, got {rd.status_code}: {rd.text}"

        # LA assigns
        r = requests.post(
            f"{API}/tours/bulk-assign",
            headers=H(tokens["la"]),
            json={"tour_ids": created_ids, "driver_id": driver_id, "driver_name": driver_name},
            timeout=15,
        )
        assert r.status_code == 200, r.text
        data = r.json()
        assert data.get("updated") == 2, data

        # Verify fields populated on each tour
        for tid in created_ids:
            rg = requests.get(f"{API}/tours", headers=H(tokens["la"]), timeout=10)
            assert rg.status_code == 200
            tours = rg.json()
            t = next((x for x in tours if x["id"] == tid), None)
            assert t is not None, f"tour {tid} disappeared"
            assert t.get("driver_id") == driver_id, t
            assert t.get("assigned_by_id"), f"assigned_by_id missing: {t}"
            assert t.get("assigned_by_name"), f"assigned_by_name missing: {t}"
            assert t.get("assigned_at"), f"assigned_at missing: {t}"
    finally:
        for tid in created_ids:
            requests.delete(f"{API}/tours/{tid}", headers=H(tokens["la"]), timeout=10)


# --------------------------------------------------------------------------
# Test 3: PUT /tours — LA sets driver_id → assigned_by_* populated;
# clearing driver_id → fields cleared
# --------------------------------------------------------------------------
def test_la_assign_via_put_populates_then_clears(tokens):
    tid = None
    try:
        body = {
            "date": "2026-06-19",
            "fraction": "TEST_p15_put_frac",
            "facility": "TEST_p15_PUT_FAC",
            "address": "TEST_p15_addr",
            "plads": "TEST_p15_plads",
            "customer_code": "PUX",
            "customer_name": "PutAssign Test",
            "tour_type": "normal",
        }
        r = requests.post(f"{API}/tours", headers=H(tokens["la"]), json=body, timeout=15)
        assert r.status_code == 200, r.text
        tid = r.json()["id"]

        drivers = requests.get(f"{API}/drivers", headers=H(tokens["la"]), timeout=10).json()
        if not drivers:
            pytest.skip("No drivers available")
        driver_id = drivers[0].get("id")
        driver_name = drivers[0].get("name") or "TestDriver"

        # Assign
        ru = requests.put(
            f"{API}/tours/{tid}",
            headers=H(tokens["la"]),
            json={"driver_id": driver_id, "driver_name": driver_name},
            timeout=15,
        )
        assert ru.status_code == 200, ru.text
        d = ru.json()
        assert d.get("driver_id") == driver_id
        assert d.get("assigned_by_id"), f"assigned_by_id should be set after assign: {d}"
        assert d.get("assigned_by_name"), d
        assert d.get("assigned_at"), d

        # Clear driver_id
        rc = requests.put(
            f"{API}/tours/{tid}",
            headers=H(tokens["la"]),
            json={"driver_id": "", "driver_name": ""},
            timeout=15,
        )
        assert rc.status_code == 200, rc.text
        d2 = rc.json()
        assert d2.get("driver_id") == ""
        # Per spec: clearing driver_id should clear assigned_by_* too
        assert d2.get("assigned_by_id", "") == "", f"assigned_by_id NOT cleared: {d2}"
        assert d2.get("assigned_by_name", "") == "", f"assigned_by_name NOT cleared: {d2}"
        assert d2.get("assigned_at", "") == "", f"assigned_at NOT cleared: {d2}"
    finally:
        if tid:
            requests.delete(f"{API}/tours/{tid}", headers=H(tokens["la"]), timeout=10)


