def H(tok):
    return {"Authorization": f"Bearer {tok}", "Content-Type": "application/json"}


# --------------------------------------------------------------------------
# Test 1: Auto-generation of tour_number
# --------------------------------------------------------------------------
def test_tour_number_autogenerated_per_prefix(tokens):
    """Creating 2 tours with same customer_code yields sequential ARG-#### codes."""
    suffix = uuid.uuid4().hex[:6].upper()
    prefix = f"P{suffix[:2]}"  # unique per run (3-char prefix)
    created_ids = []
    nums = []
    try:
        for i in range(2):
            body = {
                "date": "2026-06-19",
                "fraction": f"TEST_p15_frac_{i}",
                "facility": "TEST_p15_FAC",
                "address": "TEST_p15_addr",
                "plads": "TEST_p15_plads",
                "customer_code": prefix,
                "customer_name": "Test Customer 15",
                "tour_type": "normal",
            }
            r = requests.post(f"{API}/tours", headers=H(tokens["la"]), json=body, timeout=15)
            assert r.status_code == 200, f"create tour failed: {r.status_code} {r.text}"
            data = r.json()
            assert data.get("tour_number"), f"tour_number missing: {data}"
            assert data["tour_number"].startswith(f"{prefix}-"), data["tour_number"]
            created_ids.append(data["id"])
            nums.append(data["tour_number"])
        # Two distinct sequential numbers
        assert len(set(nums)) == 2, nums
        n1 = int(nums[0].split("-")[1])
        n2 = int(nums[1].split("-")[1])
        assert n2 == n1 + 1, f"non-sequential: {nums}"
        # Format is 4-digit zero-padded
        for n in nums:
            seq = n.split("-")[1]
            assert len(seq) == 4 and seq.isdigit(), n
    finally:
        for tid in created_ids:
            requests.delete(f"{API}/tours/{tid}", headers=H(tokens["la"]), timeout=10)


